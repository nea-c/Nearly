import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
export const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const component = '(0|[1-9][0-9]*)';
const suffix = '(?:-pre\\.([1-9][0-9]*))?';
const internalPattern = new RegExp('^'+component+'\\.'+component+'\\.0'+suffix+'$');
const tagPattern = new RegExp('^r'+component+'\\.'+component+suffix+'$');
export function displayVersion(version) {
 const m=typeof version==='string' && internalPattern.exec(version);
 if(!m || m[0]!==version || !m.slice(1).filter(x=>x!==undefined).every(x=>Number.isSafeInteger(+x)&&+x<=65535))throw Error('Version must be canonical X.Y.0 or X.Y.0-pre.N (N1..65535)');
 return 'r'+m[1]+'.'+m[2]+(m[3]?'-pre.'+m[3]:'');
}
export function internalVersion(tag) {
 const m=typeof tag==='string' && tagPattern.exec(tag);
 if(!m || m[0]!==tag)throw Error('Release tag must be canonical rX.Y or rX.Y-pre.N');
 const version=m[1]+'.'+m[2]+'.0'+(m[3]?'-pre.'+m[3]:'');displayVersion(version);return version;
}
export function compareReleaseTags(left,right) {
 const parts=tag=>{const m=internalPattern.exec(internalVersion(tag));return [+m[1],+m[2],m[3]?+m[3]:65536];};
 const a=parts(left),b=parts(right);return Math.sign(a[0]-b[0]||a[1]-b[1]||a[2]-b[2]);
}
export async function readVersion(root = projectRoot) {
  const source = JSON.parse(await fs.readFile(path.join(root, 'version.json'), 'utf8'));
  if (!source || Object.keys(source).join(',') !== 'version') throw Error('version.json must contain exactly the version field');
  const {version} = source;
  displayVersion(version);
  return version;
}
export function generatedFrontend(version) {
  return `// Generated by scripts/sync-version.mjs from version.json. Do not edit.\nexport const INTERNAL_VERSION = ${JSON.stringify(version)};\nexport function getDisplayVersion(): string { return ${JSON.stringify(displayVersion(version))}; }\n`;
}
export async function versionFiles(root = projectRoot) {
  const version = await readVersion(root), files = new Map();
  for (const name of ['package.json', 'package-lock.json', 'src-tauri/tauri.conf.json']) {
    const original = await fs.readFile(path.join(root, name), 'utf8');
    const parsed = JSON.parse(original);
    if (typeof parsed.version !== 'string') throw Error(`Missing version in ${name}`);
    // Preserve formatting and all unrelated fields, including concurrent script edits.
    let next = original.replace(/("version"\s*:\s*")[^"]+("\s*,)/, `$1${version}$2`);
    if (name === 'package-lock.json') {
      if (typeof parsed.packages?.['']?.version !== 'string') throw Error('Missing root package lock version');
      next = next.replace(/("packages"\s*:\s*\{\s*""\s*:\s*\{[^}]*?"version"\s*:\s*")[^"]+("\s*,)/, `$1${version}$2`);
    }
    files.set(name, next);
  }
  for (const name of ['src-tauri/Cargo.toml', 'src-tauri/Cargo.lock']) {
    const original = await fs.readFile(path.join(root, name), 'utf8');
    const pattern = name.endsWith('.toml') ? /(\[package\][\s\S]*?\nversion = ")[^"]+("\r?\n)/ : /(\[\[package\]\]\r?\nname = "nearly"\r?\nversion = ")[^"]+("\r?\n)/;
    if (!pattern.test(original)) throw Error(`Missing Nearly package version in ${name}`);
    files.set(name, original.replace(pattern, `$1${version}$2`));
  }
  files.set('src/version.ts', generatedFrontend(version));
  return files;
}
export async function checkVersions(root = projectRoot) {
  const drift = [];
  for (const [name, expected] of await versionFiles(root)) {
    let actual;
    try { actual = await fs.readFile(path.join(root, name), 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (actual !== expected) drift.push(name);
  }
  if (drift.length) throw Error(`Version metadata differs from version.json: ${drift.join(', ')}. Run npm run version:sync.`);
  return readVersion(root);
}
