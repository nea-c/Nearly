import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {execFileSync} from 'node:child_process';
import {verifyBootstrapTrust,loadTrustedPublicKey} from '../.github/scripts/release-trust.mjs';
const root=new URL('../',import.meta.url);
test('bootstrap profile requires registered embedded public key with installation gate still false',async t=>{
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'nearly-trust-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
  await fs.mkdir(path.join(dir,'.github'));await fs.mkdir(path.join(dir,'src-tauri/src'),{recursive:true});
  const publicBytes=await fs.readFile(new URL('.github/updater-public-key.pub',root));
  await fs.writeFile(path.join(dir,'.github/updater-public-key.pub'),publicBytes);
  const raw=await loadTrustedPublicKey(dir);
  const source=`const PRODUCTION_KEY_BYTES:[u8;42]=[${[...raw].join(',')}];\npub fn production_key()->Option<TrustedKey>{Some(TrustedKey{bytes:PRODUCTION_KEY_BYTES})}`;
  const file=path.join(dir,'src-tauri/src/update_package.rs'),gate=path.join(dir,'src-tauri/src/startup_update.rs');
  await fs.writeFile(file,source);await fs.writeFile(gate,'pub const HANDOFF_RELEASE_VALIDATED:bool=false;');
  assert.equal(await verifyBootstrapTrust(dir),true);
  for(const mutation of ['key','code','gate']){
    await fs.writeFile(file,mutation==='code'?source.replace('69,100','69,101'):source);
    await fs.writeFile(gate,`pub const HANDOFF_RELEASE_VALIDATED:bool=${mutation==='gate'?'true':'false'};`);
    await fs.writeFile(path.join(dir,'.github/updater-public-key.pub'),mutation==='key'?Buffer.concat([publicBytes,Buffer.from('x')]):publicBytes);
    await assert.rejects(()=>verifyBootstrapTrust(dir));
  }
});

test('Windows Git checkout preserves byte-pinned public key and historic public fixture',async t=>{
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'nearly-trust-checkout-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
  const files=['.github/updater-public-key.pub','tests/fixtures/reviewed-public-template.txt'];
  await fs.copyFile(new URL('.gitattributes',root),path.join(dir,'.gitattributes'));
  const expected=[];for(const file of files){await fs.mkdir(path.dirname(path.join(dir,file)),{recursive:true});const bytes=await fs.readFile(new URL(file,root));expected.push(bytes);await fs.writeFile(path.join(dir,file),bytes);}
  const git=args=>execFileSync('git',['-C',dir,'-c','core.autocrlf=true',...args],{windowsHide:true,stdio:['ignore','pipe','pipe']});
  git(['init','-b','main']);git(['add','.']);git(['-c','user.name=Generated fixture','-c','user.email=fixture@users.noreply.github.com','commit','-m','Generated byte stability fixture']);
  for(const file of files)await fs.unlink(path.join(dir,file));
  git(['checkout','--',...files]);
  for(const [index,file]of files.entries())assert.deepEqual(await fs.readFile(path.join(dir,file)),expected[index]);
});
