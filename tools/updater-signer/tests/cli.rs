use base64::{engine::general_purpose::STANDARD, Engine};
use nearly_updater_signer::{extractor_path, hash, Manifest};
use std::{
    fs,
    process::{Command, Stdio},
};
fn pe(machine: u16, magic: u16) -> Vec<u8> {
    let mut b = vec![0; 256];
    b[..2].copy_from_slice(b"MZ");
    b[0x3c..0x40].copy_from_slice(&64u32.to_le_bytes());
    b[64..68].copy_from_slice(b"PE\0\0");
    b[68..70].copy_from_slice(&machine.to_le_bytes());
    b[88..90].copy_from_slice(&magic.to_le_bytes());
    b
}
#[test]
fn generated_fixture_cli_preflight_sign_and_no_overwrite_without_secret_output() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    let payload = pe(0x8664, 0x20b);
    fs::write(root.join("Nearly.exe"), &payload).unwrap();
    let archive = root.join("fixture.zip");
    assert!(Command::new(extractor_path())
        .current_dir(root)
        .args(["a", "-tzip", "-bd", "-y"])
        .arg(&archive)
        .arg("Nearly.exe")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .unwrap()
        .success());
    let mut installer = pe(0x14c, 0x10b);
    installer.extend(fs::read(&archive).unwrap());
    let file = "Nearly_r3.1_x64-setup.exe";
    fs::write(root.join(file), &installer).unwrap();
    let m = Manifest {
        updater_protocol: 3,
        version: "3.1.0".into(),
        arch: "x64".into(),
        file: file.into(),
        source_commit: "a".repeat(40),
        artifact_id: "12345".into(),
        archive_member: "Nearly.exe".into(),
        installer_sha256: hash(&installer),
        payload_sha256: hash(&payload),
    };
    let manifest = serde_json::to_vec(&m).unwrap();
    fs::write(root.join("manifest.json"), &manifest).unwrap();
    let password = "CLI fixture password never log";
    let pair = minisign::KeyPair::generate_encrypted_keypair(Some(password.into())).unwrap();
    let key = STANDARD.encode(pair.sk.to_box(None).unwrap().to_string());
    fs::write(
        root.join("public.txt"),
        pair.pk.to_box().unwrap().to_string(),
    )
    .unwrap();
    let invoke = |mode: &str| {
        let mut c = Command::new(env!("CARGO_BIN_EXE_nearly-updater-signer"));
        c.arg(mode)
            .arg("--installer")
            .arg(root.join(file))
            .arg("--payload")
            .arg(root.join("Nearly.exe"))
            .arg("--manifest")
            .arg(root.join("manifest.json"))
            .arg("--manifest-sha256")
            .arg(hash(&manifest))
            .arg("--source-commit")
            .arg(&m.source_commit)
            .arg("--artifact-id")
            .arg(&m.artifact_id);
        if mode == "sign" {
            c.arg("--public-key")
                .arg(root.join("public.txt"))
                .arg("--ci")
                .env("NEARLY_UPDATER_PRIVATE_KEY", &key)
                .env("NEARLY_UPDATER_PRIVATE_KEY_PASSWORD", password);
        }
        c.output().unwrap()
    };
    let preflight = invoke("preflight");
    assert!(
        preflight.status.success(),
        "{}",
        String::from_utf8_lossy(&preflight.stderr)
    );
    let signed = invoke("sign");
    assert!(
        signed.status.success(),
        "{}",
        String::from_utf8_lossy(&signed.stderr)
    );
    let signature = fs::read(root.join(format!("{file}.sig"))).unwrap();
    assert!(nearly_updater_signer::verify_signature(
        &installer, &signature, &m, &pair.pk
    ));
    // Exercise the independent publisher verifier against the actual maintained
    // minisign output, not only signatures generated by its own Node fixtures.
    let node = Command::new("node")
        .args(["--input-type=module", "-e", r#"
import fs from 'node:fs';
import {pathToFileURL} from 'node:url';
const {verifyUpdaterProof}=await import(pathToFileURL(process.argv[1]));
const m=JSON.parse(fs.readFileSync(process.argv[2]));
const raw=Buffer.from(fs.readFileSync(process.argv[3],'utf8').trim().split(/\r?\n/)[1],'base64');
verifyUpdaterProof(fs.readFileSync(process.argv[4]),fs.readFileSync(process.argv[4]+'.sig'),raw,{version:m.version,file:m.file,payloadSha256:m.payloadSha256});
"#])
        .arg(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.github/scripts/updater-proof.mjs"))
        .arg(root.join("manifest.json"))
        .arg(root.join("public.txt"))
        .arg(root.join(file))
        .output()
        .unwrap();
    assert!(
        node.status.success(),
        "{}",
        String::from_utf8_lossy(&node.stderr)
    );
    assert!(!invoke("sign").status.success());
    assert_eq!(
        fs::read(root.join(format!("{file}.sig"))).unwrap(),
        signature
    );
    for output in [preflight, signed] {
        let combined = format!(
            "{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(!combined.contains(password));
        assert!(!combined.contains(&key));
    }
}
